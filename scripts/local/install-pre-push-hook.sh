#!/usr/bin/env bash
#
# Liuxian Lab — install (or refresh) the local git pre-push hook.
#
# Idempotent: safe to run repeatedly. It never overwrites an existing
# unrelated hook without first backing it up, and re-running does not stack
# duplicated content.
#
# The installed hook is a thin stub that calls the version-controlled
# checker at scripts/local/pre-push-check.sh (so the logic lives in Git).
#
set -uo pipefail

MARKER="LIUXIAN_PREPUSH_MANAGED"

ROOT="$(git rev-parse --show-toplevel 2>/dev/null)" || {
  echo "install-pre-push-hook: not inside a git repository" >&2; exit 2; }
cd "$ROOT" || exit 2

CHECK_SCRIPT="$ROOT/scripts/local/pre-push-check.sh"
HOOK_DIR="$ROOT/.git/hooks"
HOOK="$HOOK_DIR/pre-push"
BACKUP="$HOOK_DIR/pre-push.liuxian-backup"

if [ ! -f "$CHECK_SCRIPT" ]; then
  echo "install-pre-push-hook: missing $CHECK_SCRIPT" >&2; exit 2
fi

mkdir -p "$HOOK_DIR"

# --- Detect an existing, non-managed hook ---------------------------------
if [ -f "$HOOK" ] && ! grep -q "$MARKER" "$HOOK" 2>/dev/null; then
  if [ -f "$BACKUP" ]; then
    echo "  note: previous hook already backed up at $BACKUP (keeping it)"
  else
    cp "$HOOK" "$BACKUP"
    chmod +x "$BACKUP" 2>/dev/null || true
    echo "  backed up existing hook -> $BACKUP"
  fi
fi

# --- Write the managed stub (idempotent: always same content) --------------
cat > "$HOOK" <<HOOKEOF
#!/usr/bin/env bash
# $MARKER — generated by scripts/local/install-pre-push-hook.sh
# Do not edit by hand; re-run the installer to update.

set -uo pipefail
ROOT="\$(git rev-parse --show-toplevel)"

# Replay stdin to any pre-existing (backed-up) hook, then to our checker.
STDIN_TMP="\$(mktemp "\${TMPDIR:-/tmp}/liuxian-prepush.XXXXXX")"
cat > "\$STDIN_TMP"

rc=0
if [ -x "\$ROOT/.git/hooks/pre-push.liuxian-backup" ]; then
  "\$ROOT/.git/hooks/pre-push.liuxian-backup" "\$@" < "\$STDIN_TMP" || rc=\$?
fi

if [ "\$rc" -eq 0 ]; then
  "\$ROOT/scripts/local/pre-push-check.sh" --hook "\$@" < "\$STDIN_TMP"
  rc=\$?
fi

rm -f "\$STDIN_TMP"
exit "\$rc"
HOOKEOF

chmod +x "$HOOK"
chmod +x "$CHECK_SCRIPT" 2>/dev/null || true

echo "PRE-PUSH HOOK INSTALLED"
echo "  hook    : $HOOK"
echo "  checker : $CHECK_SCRIPT"
echo "  (runs QUICK checks on push; use --full manually before releases)"
